// 阶段只用于挑选文案，原始阶段字符串从不直接展示。
export function waitingBankKey(stage) {
  const text = String(stage || "");
  if (["analysis", "checking", "final", "combining"].includes(text)) return text;
  if (text.includes("合参")) return "combining";
  if (text.includes("识别问题边界")) return "intent";
  if (text.includes("逻辑校验")) return "logic";
  if (text.includes("发送")) return "final";
  if (/分析命盘|分析卦象|重新分析|重新断卦/.test(text)) return "analysis";
  return "default";
}

export function waitingLine(stage, { liuyao = false, tick = 0 } = {}) {
  const banks = liuyao ? LIUYAO_WAITING : WAITING;
  const bank = banks[waitingBankKey(stage)] || banks.default;
  return bank[Math.floor(tick / 5) % bank.length];
}

