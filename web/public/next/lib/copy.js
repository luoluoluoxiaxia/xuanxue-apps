const normalize = text => String(text || "").toLowerCase().replace(/[^一-龥a-z0-9]/g, "");
function covered(candidate, asked) {
  const a = normalize(candidate);
  return asked.some(question => {
    const b = normalize(question);
    if (!a || !b) return false;
    if (a === b) return true;
    const [short, long] = a.length <= b.length ? [a, b] : [b, a];
    return short.length >= 8 && long.includes(short);
  });
}

// 每次回答后给两条还没问过的追问建议（客户端静态题库）。
export function followupsFor({ liuyao = false, question = "", answer = "", asked = [], turn = 0 } = {}) {
  let groups = LIUYAO_FOLLOWUPS;
  if (!liuyao) {
    const hit = BANK_RULES.find(([, rule]) => rule.test(question)) || BANK_RULES.find(([, rule]) => rule.test(answer));
    groups = BAZI_FOLLOWUPS[hit ? hit[0] : "本命"];
  }
  const stage = Math.min(2, Math.max(0, turn - 1));
  const ordered = [...groups.slice(stage), ...groups.slice(0, stage)].flat().concat(FALLBACK_FOLLOWUPS);
  const picks = [];
  for (const item of ordered) {
    if (picks.length >= 2) break;
    if (!covered(item, asked) && !picks.includes(item)) picks.push(item);
  }
  return picks;
}

